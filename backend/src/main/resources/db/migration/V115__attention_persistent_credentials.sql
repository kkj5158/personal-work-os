-- Existing grants stay unchanged. Only issuance or explicit owner restore removes expiry.
ALTER TABLE attention_credentials ALTER COLUMN expires_at DROP NOT NULL;
ALTER TABLE attention_credentials ADD COLUMN last_used_at TIMESTAMPTZ;
CREATE TABLE attention_credential_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 credential_id UUID NOT NULL REFERENCES attention_credentials(id),
 user_id UUID NOT NULL REFERENCES auth.users(id),
 action VARCHAR(16) NOT NULL CHECK(action IN ('RESTORE')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE attention_credential_events ENABLE ROW LEVEL SECURITY;
