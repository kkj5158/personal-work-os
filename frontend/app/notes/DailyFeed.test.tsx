import assert from "node:assert/strict";
import { test } from "node:test";
import React, { act } from "react";
import { JSDOM } from "jsdom";
import type { Editor } from "@tiptap/core";
import type { Note, Summary, Workspace } from "@/lib/notes/types";

test("comparison preserves independent editor IDs, operational selection across dates and drafts on failed navigation", async () => {
  const dom = new JSDOM("<div id='root'></div>", { url: "https://orbit.local/notes", pretendToBeVisual: true });
  Object.assign(globalThis, { React, window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, Element: dom.window.Element, Node: dom.window.Node, MutationObserver: dom.window.MutationObserver, sessionStorage: dom.window.sessionStorage, getComputedStyle: dom.window.getComputedStyle, requestAnimationFrame: dom.window.requestAnimationFrame.bind(dom.window), cancelAnimationFrame: dom.window.cancelAnimationFrame.bind(dom.window), IS_REACT_ACT_ENVIRONMENT: true });
  Object.defineProperty(globalThis, "navigator", { value: dom.window.navigator, configurable: true });
  dom.window.Range.prototype.getClientRects = () => [] as unknown as DOMRectList;
  dom.window.Range.prototype.getBoundingClientRect = () => new dom.window.DOMRect();
  const { createRoot } = await import("react-dom/client");
  const { AppRouterContext } = await import("next/dist/shared/lib/app-router-context.shared-runtime");
  const { DailyFeed } = await import("./DailyFeed");
  const { NoteContext } = await import("./NoteContext");
  const { notesApi } = await import("@/lib/api/notes");
  const { DEFAULT_SETTINGS } = await import("@/lib/notes/types");
  const original = { ...notesApi };
  const workspace: Workspace = { id: "workspace", name: "Diet", description: "", icon: "notebook", archivedAt: null, sortOrder: 0, modules: [] };
  const record = (id: string, date: string | null): Note => ({ id, workspaceId: workspace.id, type: date ? "DAILY" : "NOTE", journalDate: date, title: date ?? `운영 ${id}`, content: `Stored ${id}`, version: 1, createdAt: "2026-10-01T00:00:00Z", updatedAt: "2026-10-01T00:00:00Z", pinnedAt: null, deletedAt: null, aliases: [], tags: [] });
  const store = new Map([record("daily-a", "2026-10-25"), record("daily-b", "2026-10-24"), record("a", null), record("b", null)].map(n => [n.id, n]));
  let order = ["a", "b"], rejectOrder = false, rejectFlush = false;
  const reorderCalls: string[][] = [], writes: string[] = [], errors: unknown[] = [];
  const summaries = (): Summary[] => order.map(id => ({ ...store.get(id)!, excerpt: "", lastOpenedAt: null }));
  notesApi.daily = async () => [...store.values()].filter(n => !!n.journalDate);
  notesApi.operationalNotes = async () => summaries();
  notesApi.note = async (_w, id) => store.get(id)!;
  notesApi.tags = async () => []; notesApi.visit = async () => {}; notesApi.wikiSuggestions = async () => [];
  notesApi.save = async (_w, input) => { writes.push(input.id); const next = { ...store.get(input.id)!, ...input, version: input.version + 1 }; store.set(input.id, next); return next; };
  notesApi.reorderOperationalNotes = async (_w, ids, expected) => { reorderCalls.push(expected); if (rejectOrder) throw new Error("order conflict"); assert.deepEqual(expected, order); order = ids; return summaries(); };
  const queues = new Map<string, () => Promise<void>>();
  const flush = async () => { if (rejectFlush) throw new Error("save blocked"); for (const save of queues.values()) await save(); };
  const router = { bfcacheId: "test", push() {}, replace() {}, refresh() {}, back() {}, forward() {}, prefetch: async () => {}, hmrRefresh() {} };
  const root = createRoot(document.getElementById("root")!);
  const render = async (date: string) => act(async () => root.render(<AppRouterContext.Provider value={router}><NoteContext.Provider value={{ workspace: workspace.id, settings: { ...DEFAULT_SETTINGS, autosaveDelay: 60000 }, openWiki() {}, error: e => errors.push(e), changed() {}, register(id, save) { queues.set(id, save); return () => { queues.delete(id); }; } }}><DailyFeed workspace={workspace} end={date} jump={() => {}} flush={flush}/></NoteContext.Provider></AppRouterContext.Provider>));
  const button = (label: string) => document.querySelector<HTMLButtonElement>(`[aria-label="${label}"]`)!;
  const choose = (title: string) => Array.from(document.querySelectorAll<HTMLButtonElement>(".operational-select")).find(n => n.textContent === title)!;
  try {
    await render("2026-10-25");
    assert.equal(document.querySelectorAll(".note-editor").length, 1);
    assert.ok(document.querySelector(".daily-index")); assert.ok(document.querySelector(".operational-notes"));
    await act(async () => choose("운영 a").click());
    assert.equal(document.querySelectorAll(".note-editor").length, 2);
    const operational = document.querySelector<HTMLElement & { editor: Editor }>(".operational-pane .tiptap")!;
    const daily = document.querySelector<HTMLElement & { editor: Editor }>(".daily-pane .tiptap")!;
    await act(() => { operational.editor.commands.insertContent(" Operation draft"); daily.editor.commands.insertContent(" Daily draft"); });
    await act(flush);
    assert.ok(writes.includes("a")); assert.ok(writes.includes("daily-a"));
    assert.match(store.get("a")!.content, /Operation draft/); assert.doesNotMatch(store.get("a")!.content, /Daily draft/);
    assert.match(store.get("daily-a")!.content, /Daily draft/); assert.doesNotMatch(store.get("daily-a")!.content, /Operation draft/);
    await render("2026-10-24");
    assert.equal(document.querySelector(".operational-pane .tiptap"), operational, "date changes retain the operational editor instance");
    assert.match(document.querySelector(".daily-pane .tiptap")!.textContent!, /Stored daily-b/);
    rejectFlush = true;
    await act(async () => choose("운영 b").click());
    assert.equal(document.querySelector(".operational-pane .tiptap"), operational, "failed flush cannot replace operational draft");
    await act(async () => button("운영 노트 닫기").click());
    assert.ok(document.querySelector(".daily-workspace.comparing")); assert.equal(errors.length, 2);
    rejectFlush = false;
    await act(async () => choose("운영 b").click());
    assert.match(document.querySelector(".operational-pane .tiptap")!.textContent!, /Stored b/);
    await act(async () => choose("운영 b").click());
    assert.equal(document.querySelector(".operational-pane"), null);
    assert.equal(document.querySelectorAll(".note-editor").length, 1);
    await act(async () => button("운영 a 아래로 이동").click());
    assert.deepEqual(order, ["b", "a"]); assert.deepEqual(reorderCalls[0], ["a", "b"]);
    rejectOrder = true;
    await act(async () => button("운영 a 위로 이동").click());
    assert.deepEqual(Array.from(document.querySelectorAll(".operational-select")).map(n => n.textContent), ["운영 b", "운영 a"], "failed order save rolls back list");
    assert.match(document.querySelector('[role="alert"]')!.textContent!, /order conflict/);
  } finally { await act(() => root.unmount()); Object.assign(notesApi, original); dom.window.close(); }
});
