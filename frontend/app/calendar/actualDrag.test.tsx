  conflicts=[{...block,id:"collision",domainType:"LIFE",sourceType:"LIFE_TIME_ENTRY",startAt:"2026-09-15T14:00:00",endAt:"2026-09-15T15:00:00"}];await act(render);
  await pointer(document.querySelector('[data-calendar-block]')!,"pointerdown",90,850);
