  cols.forEach((col,i)=>{col.getBoundingClientRect=()=>({top:0,left:48+i*100,right:148+i*100,bottom:1440,width:100,height:1440,x:48+i*100,y:0,toJSON(){}});});
  document.elementsFromPoint=(x,y)=>y>=1500 ? [document.querySelectorAll('[data-unscheduled-date]')[x>=148 ? 1 : 0]] : [];
  const pointer=async(el:Element,type:string,x:number,y:number)=>{await act(()=>{el.dispatchEvent(new dom.window.MouseEvent(type,{bubbles:true,button:0,clientX:x,clientY:y}));});};
  await pointer(document.querySelector('[data-unscheduled-source]')!,"pointerdown",90,1510);
  await pointer(content,"pointermove",190,840);await pointer(content,"pointerup",190,840);
  assert.equal(scheduled.length,1);assert.equal(scheduled[0][0],item);
